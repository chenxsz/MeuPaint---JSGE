    private ImageIcon carregarIcone(String caminho, int largura, int altura) {
        try{
            java.net.URL url = getClass().getResource(caminho);
            if(url != null) {
                javax.swing.ImageIcon iconeOriginal = new javax.swing.ImageIcon(url);
                java.awt.Image imagemRedimensionada = iconeOriginal.getImage()
                        .getScaledInstance(largura, altura, java.awt.Image.SCALE_SMOOTH);
                return new javax.swing.ImageIcon(imagemRedimensionada);
            }
        } catch(Exception e) {
            
        }
        return null;
    }

