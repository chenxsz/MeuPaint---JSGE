    private void btnCanetaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCanetaActionPerformed
        try {
            String valor = JOptionPane.showInputDialog(this, "Espessura da Caneta (1 a 50):", sldEspessura.getValue());
            if(valor != null) {
                int espessura = Integer.parseInt(valor);
                if(espessura >= 1 && espessura <= 50) {
                    sldEspessura.setValue(espessura);
                } else {
                    JOptionPane.showMessageDialog(this, "Por favor, insira um valor entre 1 e 50.", "Aviso", JOptionPane.WARNING_MESSAGE);
                }
            }
        } catch(NumberFormatException exc) {
            JOptionPane.showMessageDialog(this, "Digite apenas números inteiros.", "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnCanetaActionPerformed

